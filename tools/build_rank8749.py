"""Render the packed rank certificate data of Armillary 8749 from exported rows.

The input rows come from `tools/ExportRows8749.lean`, which prints the twelve
block-major column addresses that each retained check visits. For either sector
the script selects 907 check rows and 907 data columns whose minor is
nonsingular, records for every minor row and block which selected column is
visited, and stores one row of a right inverse of the minor as a packed word.
Tables are complete binary lookup trees of 1024 words, because the kernel reads
a tree leaf in a few steps while every access to a large array literal is slow.
Lean replays the certificate against the source route; nothing here is trusted.
"""

import argparse
import json
from pathlib import Path

ROWS = 909
MINOR = 907
SLOT_BITS = 10
SLOT_MODULUS = 1 << SLOT_BITS
TREE_LEAVES = 1024
SECTORS = {"X": 0, "Z": 1}
TARGET = Path("ArmillaryLean/Instances/RankData8749")

HEADER = """module

public import ArmillaryLean.Certificates.Numeric

@[expose] public section

/-!
# Packed rank certificate data for the {sector} sector of Armillary 8749

Generated by `tools/build_rank8749.py` from the rows that
`tools/ExportRows8749.lean` exports. The tables only carry data. Lean checks
every recorded incidence against the source route, and every inverse row by
an XOR over the row's visited columns. Every table is a complete binary lookup
tree with 1024 leaves; addresses read the tree by the bits of their index.
-/

namespace ArmillaryLean.Code8749

open ArmillaryLean.Exclusion.Numeric (WordTree)

"""


FOOTER = """
end ArmillaryLean.Code8749
"""


def read_rows(path: Path):
    rows = [[int(x) for x in line.split()] for line in path.read_text().splitlines() if line]
    if len(rows) != ROWS or any(len(row) != 12 for row in rows):
        raise ValueError(f"{path}: expected {ROWS} rows of twelve addresses")
    return rows


def select_minor(rows):
    """Pick rows in address order and the leading column of each new residual."""
    basis = {}
    chosen = []
    for r, row in enumerate(rows):
        word = 0
        for address in row:
            word |= 1 << address
        while word:
            pivot = (word & -word).bit_length() - 1
            if pivot not in basis:
                break
            word ^= basis[pivot]
        if word:
            pivot = (word & -word).bit_length() - 1
            basis[pivot] = word
            chosen.append((r, pivot))
    if len(chosen) != MINOR:
        raise ValueError(f"rank {len(chosen)} differs from {MINOR}")
    row_ids = [r for r, _ in chosen]
    column_ids = sorted(p for _, p in chosen)
    return row_ids, column_ids


def right_inverse(rows, row_ids, column_ids):
    """Return (support slots, inverse rows) for the selected minor."""
    position = {c: k for k, c in enumerate(column_ids)}
    packed = []
    support = []
    for r in row_ids:
        word = 0
        slots = []
        for address in rows[r]:
            k = position.get(address)
            slots.append(0 if k is None else k + 1)
            if k is not None:
                word |= 1 << k
        support.append(slots)
        packed.append(word)
    augmented = [packed[i] | (1 << (MINOR + i)) for i in range(MINOR)]
    pivot_row = 0
    order = []
    for col in range(MINOR):
        pivot = next((k for k in range(pivot_row, MINOR) if (augmented[k] >> col) & 1), None)
        if pivot is None:
            raise ValueError("selected minor is singular")
        augmented[pivot_row], augmented[pivot] = augmented[pivot], augmented[pivot_row]
        for k in range(MINOR):
            if k != pivot_row and (augmented[k] >> col) & 1:
                augmented[k] ^= augmented[pivot_row]
        order.append(col)
        pivot_row += 1
    inverse = [0] * MINOR
    for k, col in enumerate(order):
        inverse[col] = augmented[k] >> MINOR
    for i, r in enumerate(row_ids):
        acc = 0
        for k in range(MINOR):
            if (packed[i] >> k) & 1:
                acc ^= inverse[k]
        if acc != 1 << i:
            raise ValueError("right inverse check failed")
    return support, inverse


def tree(words):
    """Place the words of a 1024-leaf tree so that `WordTree.get k` reads word `k`."""
    words = list(words)
    if len(words) > TREE_LEAVES:
        raise ValueError("table exceeds the tree size")
    # `WordTree.get` reads the bits of the address from the low end, so leaf
    # `k` of the in-order layout sits at the bit reversal of `k`.
    bits = TREE_LEAVES.bit_length() - 1
    padded = ["0"] * TREE_LEAVES
    for k, w in enumerate(words):
        padded[int(f"{k:0{bits}b}"[::-1], 2)] = w

    def fmt(lo, hi, depth):
        if hi - lo == 1:
            return f"WordTree.leaf {padded[lo]}"
        mid = (lo + hi) // 2
        left, right = fmt(lo, mid, depth + 1), fmt(mid, hi, depth + 1)
        if depth < 4:
            return f"WordTree.fork ({left})\n  {' ' * depth}({right})"
        return f"WordTree.fork ({left}) ({right})"

    return fmt(0, TREE_LEAVES, 0)


def definition(name, type_name, literal, doc):
    return (f"/-- {doc} -/\n"
            f"def {name} : {type_name} :=\n  {literal}\n\n")


def render(sector, rows):
    row_ids, column_ids = select_minor(rows)
    support, inverse = right_inverse(rows, row_ids, column_ids)
    mask = 0
    for c in column_ids:
        mask |= 1 << c
    text = HEADER.format(sector=sector)
    text += definition(
        f"rankRows{sector}", "WordTree", tree(str(r) for r in row_ids),
        "The retained check addresses of the minor rows, in increasing order.")
    text += definition(
        f"rankColumns{sector}", "WordTree", tree(str(c) for c in column_ids),
        "The data column addresses of the minor columns, in increasing order.")
    text += definition(
        f"rankColumnMask{sector}", "Nat", hex(mask),
        "The bit mask of the selected data column addresses.")
    packed = [sum(e << (SLOT_BITS * b) for b, e in enumerate(slots)) for slots in support]
    text += definition(
        f"rankSupport{sector}", "WordTree", tree(hex(w) for w in packed),
        "For each minor row, twelve ten-bit fields; field `b` holds the selected "
        "column visited in block `b`, plus one, or zero.")
    text += definition(
        f"rankInverse{sector}", "WordTree", tree(hex(w) for w in inverse),
        "The right inverse rows of the minor; bit `j` of word `k` is entry `(k, j)`.")
    text += FOOTER
    stats = {
        "sector": sector,
        "rows": row_ids,
        "columns": column_ids,
        "support_slots": sum(1 for s in support for e in s if e),
        "inverse_weight": sum(w.bit_count() for w in inverse),
        "bytes": len(text),
    }
    return text, stats


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("dist", type=Path, help="directory holding X.rows and Z.rows")
    parser.add_argument("--summary", type=Path, help="write a JSON summary here")
    args = parser.parse_args()
    TARGET.mkdir(parents=True, exist_ok=True)
    summary = {}
    for sector in SECTORS:
        rows = read_rows(args.dist / f"{sector}.rows")
        text, stats = render(sector, rows)
        (TARGET / f"{sector}.lean").write_text(text, encoding="utf-8")
        summary[sector] = stats
        print(f"{sector}: {stats['support_slots']} slots, "
              f"inverse weight {stats['inverse_weight']}, {stats['bytes']} bytes")
    if args.summary:
        args.summary.write_text(json.dumps(summary, indent=1), encoding="utf-8")


if __name__ == "__main__":
    main()
